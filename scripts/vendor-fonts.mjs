#!/usr/bin/env node
/**
 * Copy the app's web fonts into public/fonts so the browser never asks
 * Google for them (each request would hand the visitor's IP address to
 * Google without consent). Run by hand after changing public/fonts/sources.txt,
 * for example when a new Material Symbols glyph joins the icon_names list:
 *
 *   node scripts/vendor-fonts.mjs
 *
 * sources.txt holds the Google Fonts CSS URLs, one per line. The script asks
 * for each stylesheet as a current Chrome would (woff2 with unicode ranges),
 * downloads every font file it names into public/fonts/files/ and writes
 * public/fonts/fonts.css pointing at the local copies. Fonts: Inter, JetBrains
 * Mono and Noto Sans Arabic (SIL Open Font License 1.1) and Material Symbols
 * Outlined (Apache License 2.0); see public/fonts/README.md.
 */
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const FONTS = path.join(ROOT, 'public', 'fonts');
const FILES = path.join(FONTS, 'files');
const USER_AGENT =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36';

const sources = (await readFile(path.join(FONTS, 'sources.txt'), 'utf8'))
  .split(/\r?\n/)
  .map((line) => line.trim())
  .filter((line) => line.startsWith('https://fonts.googleapis.com/'));
if (!sources.length) throw new Error('public/fonts/sources.txt lists no Google Fonts URL');

async function fetchOk(url, as) {
  const response = await fetch(url, { headers: { 'User-Agent': USER_AGENT } });
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return as === 'text' ? response.text() : Buffer.from(await response.arrayBuffer());
}

await rm(FILES, { recursive: true, force: true });
await mkdir(FILES, { recursive: true });
const sheets = [];
let count = 0;
for (const url of sources) {
  let css = await fetchOk(url, 'text');
  const urls = [...new Set([...css.matchAll(/url\((https:\/\/fonts\.gstatic\.com\/[^)]+)\)/g)].map((m) => m[1]))];
  for (const fontUrl of urls) {
    const parts = new URL(fontUrl).pathname.split('/').filter(Boolean);
    // /s/<family>/<version>/<file>.woff2, or /l/font?kit=… for the icon subset.
    const name =
      parts[0] === 's'
        ? `${parts[1]}-${parts[2]}-${parts.at(-1)}`
        : 'material-symbols-outlined.woff2';
    await writeFile(path.join(FILES, name), await fetchOk(fontUrl));
    css = css.split(fontUrl).join(`/fonts/files/${name}`);
    count += 1;
  }
  sheets.push(css.trim());
}
await writeFile(
  path.join(FONTS, 'fonts.css'),
  `/* Generated by scripts/vendor-fonts.mjs from public/fonts/sources.txt; do not edit. */\n\n${sheets.join('\n\n')}\n`,
);
console.log(`fonts.css: ${count} font files in public/fonts/files (${(await readdir(FILES)).length} on disk)`);
